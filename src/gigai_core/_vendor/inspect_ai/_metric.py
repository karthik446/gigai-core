"""Stdlib stand-in for what the lifted inspect_ai statistics files import.

Replaces inspect_ai.scorer._metric (pydantic ``Score``/``SampleScore``, the
registry-backed ``@metric``). The decorator is a passthrough: there is no
registry. ``value_to_float`` and ``is_finite_number`` keep upstream's behaviour
line for line. Recipe: S-smoke appendix A.2/A.3 (gigai-2 evals respike,
2026-11-09); typed for pyright strict in gigai-core (no ``Any``).
"""

from __future__ import annotations

import math
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from logging import getLogger
from typing import Protocol, TypeVar, Union, overload, runtime_checkable

logger = getLogger(__name__)

CORRECT = "C"
"""Value to assign for correct answers."""

INCORRECT = "I"
"""Value to assign for incorrect answers."""

PARTIAL = "P"
"""Value to assign for partial credit."""

NOANSWER = "N"
"""Value to assign for no answer or refusal to answer."""

Value = Union[
    str | int | float | bool,
    Sequence[str | int | float | bool],
    Mapping[str, str | int | float | bool | None],
]
"""Value provided by a score."""


@dataclass
class Score:
    """Score generated by a scorer (the fields the lifted statistics and scorers read)."""

    value: Value
    answer: str | None = None
    explanation: str | None = None
    reason: str | None = None
    metadata: dict[str, object] | None = None


@dataclass
class SampleScore:
    """Score for a sample."""

    score: Score
    sample_id: str | int | None = None
    sample_metadata: dict[str, object] | None = None
    scorer: str | None = None


ValueToFloat = Callable[[Value], float]
"""Function used by metrics to translate from a Score value to a float value."""


def is_finite_number(s: str) -> bool:
    """Does `s` parse as a finite float? (inspect_ai._util.text)."""
    try:
        return math.isfinite(float(s))
    except ValueError:
        return False


def value_to_float(
    correct: Value = CORRECT,
    incorrect: Value = INCORRECT,
    partial: Value = PARTIAL,
    noanswer: Value = NOANSWER,
) -> ValueToFloat:
    """Create a ValueToFloat function (upstream body, unchanged)."""

    def to_float(value: Value) -> float:
        # check the (possibly numeric) correct/incorrect/partial/noanswer values
        # before the numeric cast below, otherwise numeric custom values are
        # cast to float and passed through rather than mapped to 1/0.5/0
        if value == correct:
            return 1.0
        elif value == partial:
            return 0.5
        elif value == incorrect or value == noanswer:
            return 0.0
        elif isinstance(value, int | float | bool):
            return float(value)
        elif isinstance(value, str):
            value = value.lower()
            if value in ["yes", "true"]:
                return 1.0
            elif value in ["no", "false"]:
                return 0.0
            elif is_finite_number(value):
                return float(value)

        # couldn't extract a value
        logger.warning(f"Unable to convert value to float: {value}")
        return 0.0

    return to_float


@runtime_checkable
class MetricProtocol(Protocol):
    """A metric: a callable from the sample scores to one ``Value``."""

    def __call__(self, scores: list[SampleScore]) -> Value: ...


Metric = MetricProtocol
"""Metric protocol (upstream also accepts the pre-v0.3.64 list[Score] form)."""

MetricFactory = TypeVar("MetricFactory", bound=Callable[..., MetricProtocol])
"""A function that builds a ``Metric`` (what ``@metric`` decorates)."""


@overload
def metric(name: MetricFactory, /) -> MetricFactory: ...


@overload
def metric(name: str | None = None, /, *, scores: str = "auto") -> Callable[[MetricFactory], MetricFactory]: ...


def metric(
    name: MetricFactory | str | None = None, /, *, scores: str = "auto"
) -> MetricFactory | Callable[[MetricFactory], MetricFactory]:
    """No-registry ``@metric``: bare or with arguments, returns the factory unchanged."""
    del scores
    if callable(name):
        return name

    def unchanged(factory: MetricFactory) -> MetricFactory:
        return factory

    return unchanged
